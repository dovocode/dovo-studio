import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
const result = await build({
  stdin: {
    contents: `import {imageEditorRuntime} from './packages/client-runtime/src/images/image-editor-runtime';imageEditorRuntime(JSON.parse(document.getElementById('image-source').textContent));`,
    resolveDir: root,
  },
  bundle: true,
  write: false,
  format: 'iife',
  target: 'es2022',
  minify: true,
})
const font = await readFile(
  new URL('../packages/studio-ui/src/assets/fonts/inter-variable.woff2', import.meta.url),
)
const output = `// Generated by scripts/build-image-editor.mjs. Do not edit.\n// prettier-ignore\nexport const imageEditorScript = ${JSON.stringify(result.outputFiles[0].text)}\n// Shared offline app font for the sandboxed editor.\n// prettier-ignore\nexport const imageEditorFont = ${JSON.stringify(`data:font/woff2;base64,${font.toString('base64')}`)}\n`
const destination = new URL(
  '../packages/client-runtime/src/images/image-editor-script.ts',
  import.meta.url,
)
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== output)
    throw Error('Image editor bundle is stale. Run node scripts/build-image-editor.mjs.')
} else await writeFile(destination, output)
