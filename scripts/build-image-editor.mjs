import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
const result = await build({
  stdin: {
    contents: `import {imageEditorRuntime} from './packages/client-runtime/src/images/image-editor-runtime';imageEditorRuntime(JSON.parse(document.getElementById('image-source').textContent));`,
    resolveDir: root,
  },
  bundle: true,
  write: false,
  format: 'iife',
  target: 'es2022',
  minify: true,
})
const output = `// Generated by scripts/build-image-editor.mjs. Do not edit.\n// prettier-ignore\nexport const imageEditorScript = ${JSON.stringify(result.outputFiles[0].text)}\n`
const destination = new URL(
  '../packages/client-runtime/src/images/image-editor-script.ts',
  import.meta.url,
)
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== output)
    throw Error('Image editor bundle is stale. Run node scripts/build-image-editor.mjs.')
} else await writeFile(destination, output)
