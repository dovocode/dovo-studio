import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from './browser/harness.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const result = await build({
  stdin: {
    resolveDir: root + 'packages/studio-ui',
    contents: `
      import {createElement} from 'react';
      import {renderToStaticMarkup} from 'react-dom/server';
      import {CodeXml,SquareTerminal,Globe,Rocket,Folder,Smartphone,Database,Sparkles} from 'lucide-react';
      window.iconChoices=[['Code',CodeXml],['Terminal',SquareTerminal],['Website',Globe],['Rocket',Rocket],['Folder',Folder],['Mobile app',Smartphone],['Database',Database],['Sparkles',Sparkles]].map(([label,Icon])=>({id:'icon-'+label.toLowerCase().replaceAll(' ','-'),label,kind:'icon',svg:renderToStaticMarkup(createElement(Icon,{size:32,color:'#fff',strokeWidth:2}))}));
    `,
  },
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'iife',
})
const browser = await chromium.launch()
try {
  const page = await browser.newPage()
  await page.setContent('<html><body></body></html>')
  await page.addScriptTag({ content: result.outputFiles[0].text })
  const choices = await page.evaluate(async () => {
    const emoji = [
      ['🚀', 'Rocket'],
      ['💻', 'Laptop'],
      ['📱', 'Phone'],
      ['🌐', 'Globe'],
      ['🛠️', 'Tools'],
      ['🎨', 'Palette'],
      ['🧠', 'Brain'],
      ['🤖', 'Robot'],
      ['⚡', 'Lightning'],
      ['🔥', 'Fire'],
      ['🌱', 'Seedling'],
      ['🌊', 'Wave'],
      ['🎯', 'Target'],
      ['📦', 'Package'],
      ['🧪', 'Science'],
      ['🔒', 'Lock'],
      ['💎', 'Gem'],
      ['🦊', 'Fox'],
      ['🐱', 'Cat'],
      ['🎮', 'Game'],
      ['🎵', 'Music'],
      ['☀️', 'Sun'],
      ['⭐', 'Star'],
      ['❤️', 'Heart'],
    ].map(([text, label], i) => ({ id: 'emoji-' + i, label, kind: 'emoji', text }))
    const colors = [
      '#2563eb',
      '#7c3aed',
      '#0891b2',
      '#ea580c',
      '#d97706',
      '#db2777',
      '#059669',
      '#9333ea',
    ]
    return Promise.all(
      [...window.iconChoices, ...emoji].map(async (choice, i) => {
        const canvas = document.createElement('canvas')
        canvas.width = canvas.height = 48
        const context = canvas.getContext('2d')
        if (choice.svg) {
          context.fillStyle = colors[i % colors.length]
          context.beginPath()
          context.roundRect(0, 0, 48, 48, 10)
          context.fill()
          const image = new Image()
          image.src = 'data:image/svg+xml,' + encodeURIComponent(choice.svg)
          await image.decode()
          context.drawImage(image, 8, 8, 32, 32)
        } else {
          context.font =
            '36px "Noto Color Emoji", "Apple Color Emoji", "Segoe UI Emoji", sans-serif'
          context.textAlign = 'center'
          context.textBaseline = 'middle'
          context.fillText(choice.text, 24, 26)
        }
        return {
          id: choice.id,
          label: choice.label,
          kind: choice.kind,
          data: canvas.toDataURL('image/png'),
        }
      }),
    )
  })
  await writeFile(
    root + 'packages/protocol/src/generated/project-icon-choices.ts',
    '// Generated by scripts/generate-project-icon-choices.mjs. PNGs keep icons identical across clients.\nexport const projectIconChoices = ' +
      JSON.stringify(choices, null, 2) +
      ' as const\n',
  )
  console.log(`Generated ${choices.length} project icon choices.`)
} finally {
  await browser.close()
}
