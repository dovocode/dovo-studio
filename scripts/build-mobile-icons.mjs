import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { harnessIconData } from '../packages/protocol/src/tasks/harness-icon-data.ts'

// The React Native mapping is authoritative. Rasterize the same Lucide release for UIKit/SwiftUI.
const requireUI = createRequire(new URL('../packages/studio-ui/package.json', import.meta.url))
const lucide = requireUI('lucide-react')
const sharp = createRequire(new URL('../packages/runtime/package.json', import.meta.url))('sharp')
const { createElement } = requireUI('react')
const { renderToStaticMarkup } = requireUI('react-dom/server')
const source = await readFile(
  new URL('../apps/mobile/src/ui/controls/icon.tsx', import.meta.url),
  'utf8',
)
const mapping = source.match(/const icons = \{([\s\S]*?)\} satisfies/)?.[1] ?? ''
const icons = [...mapping.matchAll(/^\s+(\w+): (\w+),$/gm)].map((match) => [match[1], match[2]])
if (!icons.length) throw new Error('Mobile Lucide mapping not found')
const assets = new URL('../apps/mobile/assets/icons/', import.meta.url)
await mkdir(assets, { recursive: true })
for (const [name, glyph] of icons) {
  if (!lucide[glyph]) throw new Error(`Unknown Lucide icon: ${glyph}`)
  const svg = renderToStaticMarkup(
    createElement(lucide[glyph], { size: 24, color: '#ffffff', strokeWidth: 2 }),
  )
  await sharp(Buffer.from(svg))
    .resize(72, 72)
    .png()
    .toFile(fileURLToPath(new URL(`${name}@3x.png`, assets)))
}
await writeFile(
  new URL('../apps/mobile/src/ui/controls/icon-assets.ts', import.meta.url),
  `// Generated by scripts/build-mobile-icons.mjs from icon.tsx.\nimport type { ImageSourcePropType } from 'react-native'\nimport type { IconName } from './icon'\nexport const iconAssets = {\n${icons.map(([name]) => `  ${name}: require('../../../assets/icons/${name}.png'),`).join('\n')}\n} satisfies Record<IconName, ImageSourcePropType>\n`,
)
// Native text attachments cannot render React SVGs. Pass small bundled PNGs over the bridge.
const harnessImages = {}
for (const [provider, data] of Object.entries(harnessIconData)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="${data.viewBox}" fill="${data.fill ?? '#ffffff'}">${data.paths.map((path) => `<path d="${path.d}" opacity="${path.opacity ?? 1}"/>`).join('')}</svg>`
  harnessImages[provider] = {
    png: (await sharp(Buffer.from(svg)).png().toBuffer()).toString('base64'),
    template: !data.fill,
  }
}
await writeFile(
  new URL('../apps/mobile/src/agents/harness-icon-images.ts', import.meta.url),
  `// Generated by scripts/build-mobile-icons.mjs from shared harnessIconData.\nimport type { TaskHarness } from '@dovo/protocol'\nexport const harnessIconImages = {\n${Object.entries(
    harnessImages,
  )
    .map(
      ([provider, image]) =>
        `  ${provider}: {\n    png: '${image.png}',\n    template: ${image.template},\n  },`,
    )
    .join(
      '\n',
    )}\n} satisfies Record<TaskHarness['provider'], { png: string; template: boolean }>\n`,
)
