import { readFileSync } from 'node:fs'
import { expect, it, vi } from 'vite-plus/test'
import { remoteMcpAdmits } from '@dovo/protocol'
import { AccountStore } from './store.js'
import { InternetStore } from './internet-store.js'
import { RemoteMcpStore, type RemoteMcpGrant } from './remote-mcp-store.js'
import { RemoteMcpMailbox } from './remote-mcp-mailbox.js'

it('matches every admission case generated by Lean', () => {
  const path = new URL('../../../verification/remote-mcp-cases.jsonl', import.meta.url)
  const cases = readFileSync(path, 'utf8')
    .trim()
    .split('\n')
    .map(
      (line) =>
        JSON.parse(line) as { input: Parameters<typeof remoteMcpAdmits>[0]; admitted: boolean },
    )
  expect(cases).toHaveLength(64)
  for (const { input, admitted } of cases)
    expect({ input, admitted: remoteMcpAdmits(input) }).toEqual({ input, admitted })
})

it('withholds a queued call after revocation, rejects foreign claims and admits only one claimant', async () => {
  const accounts = new AccountStore(':memory:')
  try {
    const internet = new InternetStore(accounts, 'https://connect.example')
    const store = new RemoteMcpStore(accounts, internet)
    const mailbox = new RemoteMcpMailbox(store)
    const host = {
      user: 'owner',
      id: 'runtime-a',
      identity: 'identity',
      publicKey: 'public-key',
      session: 'session',
      installation: 'installation-a',
      seen: Date.now(),
    }
    const grant: RemoteMcpGrant = {
      id: 'link',
      user: host.user,
      runtimeId: host.id,
      installation: host.installation,
      parent: 'session',
      clientId: 'client',
      access: 'run',
      expires: Date.now() + 60000,
    }
    const lookup = vi.spyOn(store, 'grant').mockReturnValue(grant)
    mailbox.offer(host)
    expect(mailbox.eventsEnabled(host.installation)).toBe(false)
    await expect(
      mailbox.call(
        grant,
        { part: 'events', command: { name: 'thread.needs_input' } },
        new AbortController().signal,
      ),
    ).rejects.toThrow('does not currently offer MCP events')
    const result = mailbox.call(
      grant,
      { part: 'threads', command: { action: 'stop', id: 'thread' } },
      new AbortController().signal,
    )
    const offered = mailbox.offer(host)
    expect(offered).toBeDefined()
    const id = offered!.id
    expect(() => mailbox.claim({ ...host, installation: 'installation-b' }, id)).toThrow(
      'no longer available',
    )
    lookup.mockReturnValue(undefined)
    expect(() => mailbox.claim(host, id)).toThrow('access has changed')
    lookup.mockReturnValue(grant)
    expect(mailbox.claim(host, id).grantId).toBe(grant.id)
    expect(() => mailbox.claim(host, id)).toThrow('no longer available')
    mailbox.reply(host, { id, ok: true, result: { ok: true } })
    await expect(result).resolves.toEqual({ ok: true })
  } finally {
    accounts.db.close()
  }
})
